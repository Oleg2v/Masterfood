/**
 * Turns src/design/tokens.ts into src/app/tokens.css (a Tailwind v4 @theme block
 * plus typographic @utility presets). Runs on predev/prebuild; the output is
 * committed so a fresh clone builds even without running it.
 *
 *   npm run tokens
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  colors,
  containers,
  cubicBezier,
  durations,
  easings,
  fluidClamp,
  radii,
  shadows,
  SPACING_BASE_PX,
  typeScale,
  zLadder,
  type FontRole,
} from "../src/design/tokens.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "src/app/tokens.css");

const family: Record<FontRole, string> = {
  display: "var(--font-display)",
  ui: "var(--font-sans)",
  mono: "var(--font-mono)",
};

const L: string[] = [];
const push = (s = "") => L.push(s);

push("/*");
push(" * AUTO-GENERATED by scripts/generate-tokens.ts from src/design/tokens.ts.");
push(" * Do not edit by hand: change the tokens file and run `npm run tokens`.");
push(" */");
push();
push("@theme static {");
push("  /* Colour: the brief's eight plus the derived tints that keep the system AA. */");
push("  --color-*: initial;");
for (const c of colors) push(`  --color-${c.id}: ${c.hex}; /* ${c.en} · ${c.he} */`);
push();
push(`  /* Fluid type: 9 steps, clamp() between 360px and 1440px viewports. */`);
push("  --text-*: initial;");
for (const t of typeScale) {
  push(`  --text-${t.id}: ${fluidClamp(t.minPx, t.maxPx)}; /* step ${t.step}: ${t.minPx}→${t.maxPx}px */`);
  push(`  --text-${t.id}--line-height: round(up, ${t.lineHeight}em, 4px);`);
}
push();
push("  /* Leading comes from the type tokens (snapped to 4px); the default ratios are off-grid. */");
push("  --leading-*: initial;");
push();
push("  /* Tracking: Latin mono labels only. Hebrew is never letter-spaced. */");
push("  --tracking-*: initial;");
push("  --tracking-label: 0.08em;");
push("  --tracking-numerals: -0.02em;");
push();
push(`  /* Space: every spacing utility is a multiple of ${SPACING_BASE_PX}px (p-1 = 4px, p-6 = 24px …). */`);
push(`  --spacing: ${SPACING_BASE_PX / 16}rem;`);
push();
push("  --radius-*: initial;");
for (const r of radii) push(`  --radius-${r.id}: ${r.px >= 999 ? "9999px" : `${r.px}px`};`);
push();
push("  --z-index-*: initial;");
for (const z of zLadder) push(`  --z-index-${z.id}: ${z.z};`);
push();
for (const c of containers) push(`  --container-${c.id}: ${c.rem}rem;`);
push();
push("  --shadow-*: initial;");
for (const s of shadows) push(`  --shadow-${s.id}: ${s.css};`);
push();
push("  --ease-*: initial;");
for (const e of easings) push(`  --ease-${e.id}: ${cubicBezier(e)};`);
push();
push("  /* duration-* utilities read --transition-duration-* */");
for (const d of durations) push(`  --transition-duration-${d.id}: ${d.ms}ms;`);
push("}");
push();
push("/* Motion tokens as plain custom properties too, for keyframes and inline styles. */");
push(":root {");
for (const d of durations) push(`  --dur-${d.id}: ${d.ms}ms;`);
push("}");
push();
push("/* Typographic presets: family + size + line-height + weight in one class. */");
for (const t of typeScale) {
  push(`@utility type-${t.id} {`);
  push(`  font-family: ${family[t.family]};`);
  push(`  font-size: var(--text-${t.id});`);
  push(`  line-height: ${t.lineHeight}; /* fallback where round() is unsupported */`);
  push(`  line-height: var(--text-${t.id}--line-height); /* round(up, …, 4px): the line box sits on the 4px grid */`);
  push(`  font-weight: ${t.weight};`);
  if (t.family === "mono") push("  font-variant-numeric: tabular-nums;");
  push("}");
}
push();

const next = L.join("\n");
let prev = "";
try {
  prev = readFileSync(out, "utf8");
} catch {
  /* first run */
}
if (prev !== next) {
  writeFileSync(out, next);
  console.log(`tokens → ${out.replace(root + "/", "")} (updated)`);
} else {
  console.log("tokens → up to date");
}
